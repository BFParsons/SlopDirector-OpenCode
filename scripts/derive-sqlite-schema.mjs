#!/usr/bin/env node
/*
 * Derive a SQLite-flavoured Prisma schema from the canonical Postgres schema.
 *
 * SlopStudio Pro (desktop) ships an embedded SQLite database. Prisma 6 supports
 * almost all of this schema on SQLite unchanged — including ENUMS, which it
 * emulates as TEXT and generates the same enum types/objects as Postgres (so the
 * app's enum usage needs no changes). The only genuine incompatibilities:
 *
 *   1. No scalar lists      -> `String[]` becomes a JSON-encoded `String`
 *                              (only `StoryElement.refImageIds` today).
 *   2. PG/Docker generator  -> drop the `debian-openssl-3.0.x` binary target and
 *                              emit to an ISOLATED output dir so it never
 *                              clobbers the web (Postgres) client.
 *
 * Run: `pnpm db:sqlite:derive`
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const srcPath = join(here, "..", "prisma", "schema.prisma");
const outPath = join(here, "..", "prisma", "schema.sqlite.prisma");

const lines = readFileSync(srcPath, "utf8").split("\n");

const out = [
  "// AUTO-GENERATED by scripts/derive-sqlite-schema.mjs — DO NOT EDIT BY HAND.",
  "// SQLite variant of schema.prisma for the SlopStudio Pro desktop build.",
  "// Enums are kept (Prisma emulates them on SQLite); only scalar lists change.",
  "",
];

for (const raw of lines) {
  if (/provider\s*=\s*"postgresql"/.test(raw)) {
    out.push(raw.replace('"postgresql"', '"sqlite"'));
    continue;
  }
  // Native engine only (no Debian/Docker target). Generates to the DEFAULT
  // @prisma/client location: the desktop build runs `db:sqlite:generate` so
  // @prisma/client IS the SQLite client at runtime (no bundler alias needed);
  // the web build runs `db:generate` to restore the Postgres client.
  if (/binaryTargets\s*=/.test(raw)) {
    out.push('  binaryTargets = ["native"]');
    continue;
  }
  // Scalar list `String[]` -> JSON-encoded `String` (SQLite has no array type).
  const list = raw.match(/^(\s+)(\w+)(\s+)String(\[\])(.*)$/);
  if (list) {
    const [, indent, name, gap, , rest] = list;
    out.push(`${indent}${name}${gap}String${rest.replace(/@default\(\[\]\)/, '@default("[]")')}`);
    continue;
  }
  out.push(raw);
}

writeFileSync(outPath, out.join("\n"));
console.log(`Wrote ${outPath} (enums kept; scalar lists -> JSON String)`);
